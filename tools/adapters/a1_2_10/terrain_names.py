"""Project authored material names into the a1.2.10 client's locale catalogs."""
import json
import os
from pathlib import Path
import re
import tempfile
import unicodedata

from .terrain import game_key


SUPPORTED_LOCALES = frozenset({
    "ar", "bn", "ca", "cs", "da", "de", "de-CH", "el", "en-GB", "es", "es-419",
    "fa", "fi", "fil", "fr", "fr-CA", "he", "hi", "hu", "id", "it", "ja", "ko",
    "mr", "ms", "nb", "nl", "pl", "pt-BR", "pt-PT", "ro", "ru", "sv", "sw", "ta",
    "te", "th", "tr", "uk", "ur", "vi", "wa", "zh-Hans", "zh-Hant",
})
MARKER = b"\n\n# Generated by Innesto terrain displayNames v2\n"
PO_STRING = r'(".*"(?:\n[ \t]*".*")*)'
PO_MSGID = re.compile(rf'^(?:msgctxt[ \t]+{PO_STRING}\n)?msgid[ \t]+{PO_STRING}$', re.MULTILINE)


def validate_display_names(value):
    if not isinstance(value, dict):
        raise ValueError("displayNames must be an object")
    names = {}
    for locale, name in value.items():
        if locale not in SUPPORTED_LOCALES:
            raise ValueError(f"unsupported displayNames locale {locale!r}")
        if not isinstance(name, str):
            raise ValueError(f"displayNames[{locale!r}] must be text")
        name = unicodedata.normalize("NFC", name)
        if (not 1 <= len(name) <= 64 or name != name.strip()
                or any(unicodedata.category(c).startswith("C") or unicodedata.category(c) in {"Zl", "Zp"}
                       for c in name)):
            raise ValueError(f"displayNames[{locale!r}] must be 1–64 single-line characters without controls or padding")
        names[locale] = name
    return dict(sorted(names.items()))


def _read_catalog(path):
    if path.is_symlink() or not path.is_file():
        raise ValueError(f"missing or linked terrain name catalog {path.name!r}")
    return path.read_bytes()


def _reject_occupied(raw, wanted):
    # Both the shipped PO files and our additions use quoted strings. A source
    # string can also span several adjacent quoted lines.
    for context, literal in PO_MSGID.findall(raw.decode("utf-8").replace("\r\n", "\n")):
        if context and any(json.loads(part.strip()) for part in context.splitlines()):
            continue
        key = "".join(json.loads(part.strip()) for part in literal.splitlines())
        if key in wanted:
            raise ValueError(f"terrain display name lookup collision for {key!r}")


def stage_display_names(runtime_assets: Path, materials):
    """Extend catalogs only in the caller's copied client asset tree."""
    by_locale = {}
    for material in materials:
        for locale, name in validate_display_names(getattr(material, "display_names", {})).items():
            source = game_key(material.id).replace("_", " ").capitalize()
            translations = by_locale.setdefault(locale, {})
            if source in translations and translations[source] != name:
                raise ValueError(f"terrain display name lookup collision for {source!r}")
            translations[source] = name
    if not by_locale:
        return
    directory = runtime_assets / "lang"
    if directory.is_symlink() or not directory.is_dir():
        raise ValueError("missing or linked terrain language directory")
    wanted = {key for translations in by_locale.values() for key in translations}
    _reject_occupied(_read_catalog(directory / "openworld.pot"), wanted)
    outputs = {}
    for locale, translations in sorted(by_locale.items()):
        path = directory / f"{locale}.po"
        existing = _read_catalog(path)
        original, separator, _ = existing.partition(MARKER)
        _reject_occupied(original, translations)
        entries = []
        for key, name in sorted(translations.items()):
            entries.append(f'msgid {json.dumps(key)}\nmsgstr {json.dumps(name, ensure_ascii=False)}\n')
        output = original + MARKER + "\n".join(entries).encode("utf-8")
        if existing != output:
            if separator:
                raise ValueError("terrain catalog already staged for different display names")
            outputs[path] = output
    if outputs:
        # copytree preserves the stock directory permissions. Replace only
        # private directory entries, including when the source files are read-only.
        directory.chmod(directory.stat().st_mode | 0o700)
    for path, output in outputs.items():
        with tempfile.NamedTemporaryFile(dir=directory, delete=False) as stream:
            temporary = Path(stream.name)
            try:
                stream.write(output)
                stream.flush()
                os.replace(temporary, path)
            finally:
                temporary.unlink(missing_ok=True)
